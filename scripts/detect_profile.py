#!/usr/bin/env python3
"""Derive .governance/profile.yml from a repository's manifests.

  detect_profile.py [--repo-dir .] [--write] [--json]

Signals: pyproject.toml / setup.py, package.json, Cargo.toml, go.mod, CLI entry points,
deploy configuration, locale files, fuzz harnesses, docs tooling. Fields that cannot be
derived reliably are listed under `uncertain`; the owner confirms them during onboarding.
governance-audit fails while `uncertain` is not empty.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import govlib  # noqa: E402

WEB_DEPS = {"react", "vue", "svelte", "next", "nuxt", "vite", "@angular/core", "solid-js", "astro", "@sveltejs/kit", "preact"}
DEPLOY_FILES = ["fly.toml", "render.yaml", "vercel.json", "netlify.toml", "app.yaml", "Procfile", "railway.json", "wrangler.toml", "serverless.yml"]
SET_VERSION = 'python3 "$GOV/scripts/set_version.py" "$VERSION"'
HEADER = "# Project parameters for nullthrone/governance. Owner-only file (protected).\n# Generated by scripts/detect_profile.py; fields listed in `uncertain` need the owner's confirmation.\n"


def _read_toml(path: Path) -> dict:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def detect_languages(root: Path) -> list[str]:
    found = []
    if (root / "pyproject.toml").exists() or (root / "setup.py").exists() or (root / "setup.cfg").exists():
        found.append("python")
    if (root / "package.json").exists():
        found.append("node")
    if (root / "Cargo.toml").exists():
        found.append("rust")
    if (root / "go.mod").exists():
        found.append("go")
    return found


def detect_locales(root: Path) -> list[str]:
    locales: set[str] = set()
    code = re.compile(r"^[a-z]{2,3}(?:[_-][A-Za-z]{2,4})?$")
    for base in ("locales", "locale", "i18n", "lang", "translations", "src/locales", "src/i18n", "public/locales"):
        d = root / base
        if not d.is_dir():
            continue
        for entry in d.iterdir():
            name = entry.stem if entry.is_file() else entry.name
            if code.match(name):
                locales.add(name)
    for po in root.glob("**/LC_MESSAGES/*.po"):
        locales.add(po.parent.parent.name)
    for po in (root / "po").glob("*.po") if (root / "po").is_dir() else []:
        locales.add(po.stem)
    return sorted(loc for loc in locales if not loc.lower().startswith("en"))


def discover_fuzz_targets(root: Path, language: str) -> list[dict]:
    targets: list[dict] = []
    if language == "rust" and (root / "fuzz" / "fuzz_targets").is_dir():
        for f in sorted((root / "fuzz" / "fuzz_targets").glob("*.rs")):
            targets.append({"name": f.stem, "command": f"cargo +nightly fuzz run {f.stem} -- -max_total_time={{seconds}}", "crash_dir": f"fuzz/artifacts/{f.stem}"})
    elif language == "go":
        for f in sorted(root.glob("**/*_test.go")):
            if "vendor/" in f.as_posix():
                continue
            for name in re.findall(r"^func (Fuzz\w+)\(", f.read_text(encoding="utf-8", errors="ignore"), re.MULTILINE):
                pkg = "./" + f.parent.relative_to(root).as_posix() if f.parent != root else "."
                targets.append({"name": name, "command": f"go test -run=^$ -fuzz=^{name}$ -fuzztime={{seconds}}s {pkg}", "crash_dir": f"{pkg.lstrip('./') or '.'}/testdata/fuzz/{name}"})
    elif language == "python" and (root / "fuzz").is_dir():
        for f in sorted((root / "fuzz").glob("*.py")):
            if "atheris" in f.read_text(encoding="utf-8", errors="ignore"):
                targets.append({"name": f.stem, "command": f"python fuzz/{f.name} -max_total_time={{seconds}} -artifact_prefix=fuzz/crashes/", "crash_dir": "fuzz/crashes"})
    elif language == "node" and (root / "fuzz").is_dir():
        for f in sorted((root / "fuzz").glob("*.fuzz.[jt]s")):
            targets.append({"name": f.stem.replace(".fuzz", ""), "command": f"npx jazzer fuzz/{f.name} -- -max_total_time={{seconds}}", "crash_dir": "."})
    return targets


def _python(root: Path, prof: dict, uncertain: list[str]) -> None:
    py = _read_toml(root / "pyproject.toml")
    project = py.get("project", {})
    name = project.get("name") or root.name
    import_name = name.replace("-", "_").lower()
    src = "src" if (root / "src" / import_name).is_dir() else "."
    scripts = project.get("scripts", {})
    optional = project.get("optional-dependencies", {})
    deps_text = json.dumps(py).lower()
    req = project.get("requires-python", "")
    m = re.search(r">=\s*3\.(\d+)", req)
    prof["runtime_version"] = f"3.{max(int(m.group(1)), 12)}" if m else "3.12"
    prof["package"] = {"name": name, "import_name": import_name, "publish": "pypi" if project and (root / "pyproject.toml").exists() else "none"}
    if not project:
        uncertain.append("package.publish")
    extras = "dev" if "dev" in optional else ("test" if "test" in optional else None)
    setup = f'python -m pip install -e ".[{extras}]"' if extras else "python -m pip install -e ."
    if "pytest" in deps_text or (root / "tests").is_dir() or (root / "pytest.ini").exists():
        test = "pytest -q"
        if "pytest" not in json.dumps(optional).lower():
            setup += " pytest"
    else:
        test = "python -m unittest discover -v"
    cmds = {"setup": setup, "build": "python -m pip install -q build && python -m build", "test": test}
    if "ruff" in deps_text or (root / "ruff.toml").exists() or (root / ".ruff.toml").exists():
        cmds["lint"] = "ruff check ."
    if scripts:
        script = sorted(scripts)[0]
        cmds["version"] = f"{script} --version"
        prof["profiles"].append("cli")
        prof["classification"]["surface"] = [f"{script} --help"]
        uncertain.append("commands.version")
    else:
        cmds["version"] = f"python -c \"import importlib.metadata as m; print(m.version('{name}'))\""
    cmds["set_version"] = SET_VERSION
    if not scripts and (project or (root / src / import_name / "__init__.py").exists()):
        prof["profiles"].append("library")
        prof["classification"]["api"] = "griffe"
        prof["classification"]["search_path"] = src
        cmds["doctest"] = f"pytest -q --doctest-modules {src if src != '.' else import_name}"
        uncertain.append("commands.doctest")
    prof["commands"] = cmds
    prof["artifacts"] = "dist/*"
    prof["housekeeping"]["dead_code"] = f"python -m pip install -q vulture && vulture {src if src != '.' else import_name} --min-confidence 80"


def _node(root: Path, prof: dict, uncertain: list[str]) -> None:
    pkg = _read_json(root / "package.json")
    scripts = pkg.get("scripts", {})
    deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
    engines = str(pkg.get("engines", {}).get("node", ""))
    m = re.search(r"(\d{2})", engines)
    prof["runtime_version"] = m.group(1) if m else "22"
    name = pkg.get("name") or root.name
    private = bool(pkg.get("private"))
    prof["package"] = {"name": name, "publish": "none" if private else "npm"}
    if private:
        uncertain.append("package.publish")
    cmds = {"setup": "npm ci" if (root / "package-lock.json").exists() else "npm install", "test": "npm test"}
    if "lint" in scripts:
        cmds["lint"] = "npm run lint"
    if "build" in scripts:
        cmds["build"] = "npm run build"
    bin_field = pkg.get("bin")
    if bin_field:
        bin_path = bin_field if isinstance(bin_field, str) else sorted(bin_field.values())[0]
        cmds["version"] = f"node {bin_path} --version"
        prof["profiles"].append("cli")
        prof["classification"]["surface"] = [f"node {bin_path} --help"]
        uncertain.append("commands.version")
    else:
        cmds["version"] = "node -p \"require('./package.json').version\""
    cmds["set_version"] = 'npm version "$VERSION" --no-git-tag-version --allow-same-version'
    if WEB_DEPS & set(deps):
        prof["profiles"].append("web")
        uncertain.append("profiles")
    if not private and (pkg.get("main") or pkg.get("exports") or pkg.get("module")):
        prof["profiles"].append("library")
        if (root / "api-extractor.json").exists():
            prof["classification"]["api"] = "api-extractor"
        else:
            uncertain.append("classification.api")
    if "@playwright/test" in deps:
        cmds["e2e"] = "npx playwright install --with-deps && npx playwright test"
        cmds["screenshots"] = "npx playwright test --grep @screenshot"
        uncertain.append("commands.screenshots")
    prof["commands"] = cmds
    prof["housekeeping"]["dead_code"] = "npx --yes knip"


def _rust(root: Path, prof: dict, uncertain: list[str]) -> None:
    cargo = _read_toml(root / "Cargo.toml")
    package = cargo.get("package", {})
    name = package.get("name") or root.name
    prof["runtime_version"] = str(package.get("rust-version") or "stable")
    prof["package"] = {"name": name, "publish": "none" if package.get("publish") is False else "crates"}
    cmds = {
        "setup": "cargo fetch",
        "build": "cargo build --release",
        "test": "cargo test --all-features",
        "lint": "cargo clippy --all-targets -- -D warnings && cargo fmt --check",
        "set_version": SET_VERSION,
    }
    is_bin = (root / "src" / "main.rs").exists() or bool(cargo.get("bin"))
    if is_bin:
        cmds["version"] = "cargo run --quiet --release -- --version"
        prof["profiles"].append("cli")
        prof["classification"]["surface"] = ["cargo run --quiet --release -- --help"]
        prof["artifacts"] = f"target/release/{name}"
        uncertain.append("commands.version")
    if (root / "src" / "lib.rs").exists() or cargo.get("lib"):
        prof["profiles"].append("library")
        prof["classification"]["api"] = "cargo-semver-checks"
        cmds.setdefault("version", "cargo pkgid | sed -E 's/.*[#@]//'")
        cmds["doctest"] = "cargo test --doc"
    cmds.setdefault("version", "cargo pkgid | sed -E 's/.*[#@]//'")
    prof["commands"] = cmds
    prof["housekeeping"]["dead_code"] = "cargo check --all-targets 2>&1 | grep -E 'never (used|read|constructed)' || true"


def _go(root: Path, prof: dict, uncertain: list[str]) -> None:
    text = (root / "go.mod").read_text(encoding="utf-8", errors="ignore")
    module = re.search(r"^module\s+(\S+)", text, re.MULTILINE)
    version = re.search(r"^go\s+(\S+)", text, re.MULTILINE)
    prof["runtime_version"] = version.group(1) if version else "stable"
    prof["package"] = {"name": module.group(1) if module else root.name, "publish": "none"}
    cmds = {"setup": "go mod download", "build": "go build ./...", "test": "go test ./...", "lint": "go vet ./..."}
    has_main = any("package main" in f.read_text(encoding="utf-8", errors="ignore") for f in root.glob("**/*.go") if "vendor/" not in f.as_posix() and not f.name.endswith("_test.go"))
    if has_main:
        cmds["version"] = "go run . --version"
        prof["profiles"].append("cli")
        prof["classification"]["surface"] = ["go run . --help"]
        uncertain.append("commands.version")
    else:
        prof["profiles"].append("library")
        prof["classification"]["api"] = "go-doc"
        cmds["version"] = "git describe --tags --abbrev=0 | sed 's/^v//'"
        uncertain.append("commands.version")
    prof["commands"] = cmds
    prof["housekeeping"]["dead_code"] = "go run golang.org/x/tools/cmd/deadcode@latest ./..."


def fuzz_targets(profile: dict, root: Path) -> list[dict]:
    """Explicit fuzz.targets, or targets discovered by convention when fuzz.auto is true."""
    explicit = govlib.dig(profile, "fuzz.targets")
    if explicit:
        return explicit
    if govlib.dig(profile, "fuzz.auto"):
        return discover_fuzz_targets(root, str(profile.get("language") or "other"))
    return []


def detect(root: Path) -> dict:
    languages = detect_languages(root)
    uncertain: list[str] = []
    language = languages[0] if languages else "other"
    if len(languages) > 1:
        uncertain.append("language")
    prof: dict = {
        "version": 1,
        "language": language,
        "runtime_version": "",
        "profiles": [],
        "package": {"name": root.name, "publish": "none"},
        "commands": {},
        "classification": {"api": "none", "surface": []},
        "artifacts": "",
        "docs": {"site": False, "locales": []},
        "preview": {"type": "artifact"},
        "housekeeping": {"dead_code": "", "web_checks": []},
        "fuzz": {"auto": True},
    }
    {"python": _python, "node": _node, "rust": _rust, "go": _go}.get(language, lambda *a: None)(root, prof, uncertain)
    if language == "other":
        uncertain += ["language", "commands.test", "commands.version"]
        prof["commands"] = {"test": "", "version": ""}

    if any((root / f).exists() for f in DEPLOY_FILES) or (root / "Dockerfile").exists() and (root / "docker-compose.yml").exists():
        prof["profiles"].append("service")
        prof["commands"]["deploy"] = ""
        prof["commands"]["smoke"] = ""
        uncertain += ["commands.deploy", "commands.smoke"]
    if "web" in prof["profiles"]:
        prof["preview"]["type"] = "deployment" if "service" in prof["profiles"] else "artifact"
        prof["housekeeping"]["web_checks"] = []
        uncertain += ["preview.type", "housekeeping.web_checks"]
    elif "library" in prof["profiles"] and prof["package"]["publish"] == "pypi":
        prof["preview"]["type"] = "testpypi"

    # Processes untrusted input? Cannot be derived; propose from CLI/parser signals.
    if "cli" in prof["profiles"] or any(root.glob("**/*pars*.*")):
        prof["profiles"].append("input-processing")
    uncertain.append("profiles")

    docs = prof["docs"]
    if (root / "mkdocs.yml").exists():
        docs.update({"site": True, "build": "python -m pip install -q mkdocs-material mkdocstrings[python] && mkdocs build --strict", "output": "site"})
    elif (root / "docusaurus.config.js").exists() or (root / "docusaurus.config.ts").exists():
        docs.update({"site": True, "build": "npm run build --prefix website || npx docusaurus build", "output": "build"})
    elif "library" in prof["profiles"]:
        docs["site"] = True
        uncertain.append("docs.build")
        docs["build"] = ""
        docs["output"] = "site"
    docs["locales"] = detect_locales(root)

    prof["profiles"] = sorted(set(prof["profiles"]))
    if not prof["artifacts"] and language == "node" and prof["package"]["publish"] == "npm":
        prof["artifacts"] = ""
    prof["uncertain"] = sorted(set(uncertain))
    return prof


def compare(existing: dict, detected: dict) -> list[str]:
    """Fields where the committed profile contradicts the repository's manifests."""
    problems = []
    if existing.get("language") != detected.get("language") and "language" not in detected.get("uncertain", []):
        problems.append(f"language: profile says {existing.get('language')!r}, manifests say {detected.get('language')!r}")
    if govlib.dig(existing, "package.name") != govlib.dig(detected, "package.name") and detected.get("language") != "other":
        problems.append(f"package.name: profile {govlib.dig(existing, 'package.name')!r} vs manifest {govlib.dig(detected, 'package.name')!r}")
    for kind in ("cli", "library"):
        if kind in detected.get("profiles", []) and kind not in (existing.get("profiles") or []):
            problems.append(f"profiles: manifests indicate '{kind}', profile does not list it")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo-dir", default=".")
    parser.add_argument("--write", action="store_true", help="write .governance/profile.yml (only if missing, unless --force)")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    root = Path(args.repo_dir).resolve()
    prof = detect(root)
    if args.json:
        print(json.dumps(prof, indent=2))
    else:
        print(HEADER + govlib.yaml_dump(prof), end="")
    if args.write:
        target = root / govlib.PROFILE_PATH
        if target.exists() and not args.force:
            print(f"{target} exists; not overwritten (use --force)", file=sys.stderr)
            return 0
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(HEADER + govlib.yaml_dump(prof), encoding="utf-8")
        print(f"wrote {target}; uncertain: {', '.join(prof['uncertain']) or 'none'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
